import type { IdeasRequest } from "./schema.js";

const RELATION_LABELS: Record<IdeasRequest["people"][number]["relation"], string> = {
  family: "член семьи",
  close: "близкий друг",
  friend: "друг или приятель",
  colleague: "коллега",
  other: "знакомый",
};

export const SYSTEM_PROMPT = `Ты — личный помощник в мобильном календаре. Пользователь живёт в Казахстане и не хочет пропускать дни рождения близких, государственные и профессиональные праздники. Когда приходит напоминание, ты помогаешь подготовиться: предлагаешь подарки и пишешь поздравления.

Подарки:
- Предлагай 4–6 разных идей: от практичных до впечатлений (ужин, мастер-класс, поездка), а для коллег и профессиональных праздников — уместные и недорогие.
- Опирайся на интересы, возраст, отношения и повод. Если о человеке мало данных, предлагай универсальные, но не банальные варианты.
- Учитывай, сколько дней осталось: если меньше 3 дней, предлагай то, что можно купить или заказать быстро.
- Цены указывай примерным диапазоном в тенге (₸). Если задан бюджет, укладывайся в него.
- Учитывай местные традиции (например, на Наурыз, Курбан айт, юбилеи у старших родственников).

Поздравления:
- Напиши 2–3 варианта: тёплое личное, короткое для мессенджера и, если уместно, более официальное (для коллег и старших).
- Обращайся к человеку по имени. Без штампов и излишнего пафоса.
- Казахский текст пиши естественно, как написал бы носитель языка, а не дословным переводом с русского. Уместны принятые обращения (апа, аға, әже, ата и т.п.), если подходят по возрасту и родству.
- Если в поводе несколько человек (например, коллеги в профессиональный праздник), напиши поздравление, которое подойдёт каждому.

Советы: 1–3 коротких практичных совета (что сделать заранее, кого ещё не забыть поздравить).`;

export function buildUserPrompt(req: IdeasRequest): string {
  const { occasion, people, budget, language, exclude } = req;
  const lines: string[] = [];

  lines.push(`Повод: ${occasion.title}`);
  lines.push(
    `Дата: ${occasion.date} (${occasion.daysLeft === 0 ? "сегодня" : `через ${occasion.daysLeft} дн.`})`,
  );
  if (occasion.kind === "holiday" && occasion.holidayKind) {
    const kindLabel = {
      state: "государственный праздник Казахстана",
      religious: "религиозный праздник",
      professional: "профессиональный праздник",
      other: "праздник",
    }[occasion.holidayKind];
    lines.push(`Тип: ${kindLabel}`);
  }

  if (people.length > 0) {
    lines.push("", "Кого поздравляем:");
    for (const p of people) {
      const parts = [`${p.name} — ${RELATION_LABELS[p.relation]}`];
      if (p.age !== undefined) parts.push(`возраст: ${p.age}`);
      if (p.gender) parts.push(p.gender === "male" ? "мужчина" : "женщина");
      if (p.profession) parts.push(`профессия: ${p.profession}`);
      if (p.interests) parts.push(`интересы: ${p.interests}`);
      if (p.notes) parts.push(`заметки: ${p.notes}`);
      lines.push(`- ${parts.join("; ")}`);
    }
  } else {
    lines.push("", "Конкретные люди не указаны: предложи идеи для близких и коллег в целом.");
  }

  if (budget) lines.push("", `Бюджет: ${budget}`);
  if (exclude.length > 0) {
    lines.push("", `Эти идеи уже предлагались, придумай другие: ${exclude.join("; ")}`);
  }

  lines.push(
    "",
    {
      ru: "Поздравления напиши на русском языке.",
      kk: "Поздравления напиши на казахском языке.",
      both: "Каждый вариант поздравления напиши дважды: на русском и на казахском — отдельными элементами с одинаковым style.",
    }[language],
    "Подарки и советы — на русском.",
  );

  return lines.join("\n");
}
